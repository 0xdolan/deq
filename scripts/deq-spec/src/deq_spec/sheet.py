"""Contact sheets: every shape on its grid, and the logo concepts in several treatments."""

from __future__ import annotations

from collections.abc import Mapping
from typing import Any
from xml.sax.saxutils import escape

from deq_spec import metrics, render
from deq_spec.spec import Json, Registry, expand

HEADER = "<!-- Generated by `uv run deq-spec sheet`. Do not edit; edit spec/ and regenerate. -->\n"
FONT = "font-family=\"system-ui, -apple-system, 'Segoe UI', sans-serif\""
INK = "#1d1d1f"
MUTED = "#6e6e73"
GRID = "#d9d9de"
FLAG = {"red": "#ED2024", "white": "#FFFFFF", "green": "#278E43", "yellow": "#FEBD11"}

CELL_W, CELL_H = 168, 176
COLS = 6
BIG = 3.0


def _grid(x: float, y: float, s: float) -> str:
    """Live area and the circle keyline behind a shape drawn at scale ``s``."""
    return (
        f'<g transform="translate({x} {y}) scale({s})" fill="none" stroke="{GRID}" '
        f'stroke-width="{0.5 / s:.3f}">'
        f'<rect x="1" y="1" width="22" height="22"/><circle cx="12" cy="12" r="10"/>'
        f'<line x1="12" y1="1" x2="12" y2="23"/><line x1="1" y1="12" x2="23" y2="12"/></g>'
    )


def _place(
    items: list[Any],
    x: float,
    y: float,
    s: float,
    *,
    color: str,
    layer_colors: Mapping[str, str] | None = None,
) -> str:
    body = render.group(items, color=color, layer_colors=layer_colors)
    return f'<g transform="translate({x} {y}) scale({s})">{body}</g>'


def _variations(shape: Json) -> list[dict[str, Any]]:
    """Up to four non-default settings, one parameter at a time."""
    out: list[dict[str, Any]] = []
    for name, decl in shape["parameters"].items():
        for combo in metrics.combos({name: decl}):
            if combo[name] != decl["default"]:
                out.append(combo)
    return out[:4]


def _label(combo: dict[str, Any]) -> str:
    return ", ".join(f"{k}={str(v).lower()}" for k, v in combo.items())


def shapes_sheet(reg: Registry, catalog: Json) -> str:
    rows: list[str] = []
    y = 64.0
    for cat in catalog["categories"]:
        rows.append(
            f'<text x="24" y="{y + 18}" font-size="16" font-weight="600" fill="{INK}">'
            f"{escape(cat['name'])}</text>"
        )
        y += 32
        for i, sid in enumerate(cat["shapes"]):
            shape = reg.get(sid)
            cx = 24 + (i % COLS) * CELL_W
            cy = y + (i // COLS) * CELL_H
            gx = cx + (CELL_W - 24 * BIG) / 2 - 12
            rows.append(_grid(gx, cy, BIG))
            rows.append(_place(expand(shape, reg), gx, cy, BIG, color=INK))
            rows.append(
                f'<text x="{cx + CELL_W / 2 - 12}" y="{cy + 24 * BIG + 16}" text-anchor="middle" '
                f'font-size="11" fill="{INK}">{escape(sid)}</text>'
            )
            for k, combo in enumerate(_variations(shape)):
                vx = cx + 6 + k * 38
                vy = cy + 24 * BIG + 26
                rows.append(_grid(vx, vy, 1.25))
                rows.append(
                    f"<g><title>{escape(_label(combo))}</title>"
                    f"{_place(expand(shape, reg, combo), vx, vy, 1.25, color=INK)}</g>"
                )
        y += ((len(cat["shapes"]) + COLS - 1) // COLS) * CELL_H + 16
    width = 24 * 2 + COLS * CELL_W
    title = (
        f'<text x="24" y="40" font-size="22" font-weight="700" fill="{INK}">Deq shapes</text>'
        f'<text x="{width - 24}" y="40" text-anchor="end" font-size="12" fill="{MUTED}">'
        "24 x 24 grid, stroke 2, defaults large; "
        "small: one parameter changed (hover for values)</text>"
    )
    return _doc(width, y + 8, title + "".join(rows))


def _doc(width: float, height: float, body: str) -> str:
    return (
        HEADER + f'<svg xmlns="http://www.w3.org/2000/svg" width="{width:g}" height="{height:g}" '
        f'viewBox="0 0 {width:g} {height:g}" {FONT}>'
        f'<rect width="100%" height="100%" fill="#ffffff"/>{body}</svg>\n'
    )


def _flag_colors(layers: list[str]) -> dict[str, str]:
    cycle = [FLAG["red"], FLAG["green"], FLAG["yellow"]]
    return {layer: cycle[i % len(cycle)] for i, layer in enumerate(layers)}


def concepts_sheet(reg: Registry, concept_ids: list[str]) -> str:
    """One row per concept: mono, flag colours, reversed, on red and green, then 48/32/16 px."""
    tile = 120
    rows: list[str] = []
    y = 72.0
    for cid in concept_ids:
        shape = reg.get(cid)
        items = expand(shape, reg)
        s = (tile - 24) / 24
        treatments = [
            ("mono", "#ffffff", {}, INK),
            ("flag colours", "#ffffff", _flag_colors(shape["layers"]), INK),
            ("reversed", INK, {}, "#ffffff"),
            ("on red", FLAG["red"], {}, "#ffffff"),
            ("on green", FLAG["green"], {}, FLAG["yellow"]),
        ]
        rows.append(
            f'<text x="24" y="{y - 10}" font-size="14" font-weight="600" fill="{INK}">'
            f"{escape(cid)}: {escape(shape['names']['en'])}</text>"
        )
        for k, (name, bg, layer_colors, color) in enumerate(treatments):
            x = 24 + k * (tile + 12)
            rows.append(
                f'<rect x="{x}" y="{y}" width="{tile}" height="{tile}" rx="12" '
                f'fill="{bg}" stroke="{GRID}"/>'
            )
            rows.append(_place(items, x + 12, y + 12, s, color=color, layer_colors=layer_colors))
            rows.append(
                f'<text x="{x + tile / 2}" y="{y + tile + 16}" text-anchor="middle" '
                f'font-size="11" fill="{MUTED}">{name}</text>'
            )
        x = 24 + 5 * (tile + 12)
        for px in (48, 32, 16):
            rows.append(_place(items, x, y + (tile - px) / 2, px / 24, color=INK))
            rows.append(
                f'<text x="{x + px / 2}" y="{y + tile + 16}" text-anchor="middle" '
                f'font-size="11" fill="{MUTED}">{px}px</text>'
            )
            x += px + 20
        y += tile + 56
    width = 24 * 2 + 5 * (tile + 12) + 48 + 32 + 16 + 60
    title = (
        f'<text x="24" y="36" font-size="22" font-weight="700" fill="{INK}">'
        "Deq logo concepts (symbol only)</text>"
    )
    return _doc(width, y, title + "".join(rows))
