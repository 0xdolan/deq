/**
 * Builds `src/generated/shapes.ts` from `spec/catalog.json` and `spec/shapes/*.json`.
 *
 *   node scripts/generate-shapes.ts           write the file
 *   node scripts/generate-shapes.ts --check   fail if the file is out of date
 */
import { closeSync, constants, fstatSync, openSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import type { ShapeData } from "../src/types.ts";

const here = dirname(fileURLToPath(import.meta.url));
export const SPEC_DIR = join(here, "..", "..", "..", "spec");
export const OUT_FILE = join(here, "..", "src", "generated", "shapes.ts");

/** Largest spec file accepted (bytes), the same limit as `deq-spec`. */
const MAX_FILE_BYTES = 256 * 1024;
const ID = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

interface Catalog {
  readonly categories: readonly { readonly shapes: readonly unknown[] }[];
}

/** A spec shape file: everything in {@link ShapeData} plus documentation fields. */
type SpecShape = ShapeData & Record<string, unknown>;

/** `O_NOFOLLOW` where the platform has it (not on Windows). */
const NOFOLLOW: number = (constants as Partial<typeof constants>).O_NOFOLLOW ?? 0;

/**
 * Read a regular file as UTF-8, refusing symlinks and files over `maxBytes`. The file is
 * opened once and checked through its descriptor, so it cannot be swapped between the
 * check and the read.
 */
export function readText(path: string, maxBytes: number = MAX_FILE_BYTES): string {
  let fd: number;
  try {
    fd = openSync(path, constants.O_RDONLY | NOFOLLOW);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ELOOP")
      throw new Error(`${path}: refusing symlink`, { cause: err });
    throw err;
  }
  try {
    const st = fstatSync(fd);
    if (!st.isFile()) throw new Error(`${path}: not a regular file`);
    if (st.size > maxBytes) throw new Error(`${path}: larger than ${String(maxBytes)} bytes`);
    return readFileSync(fd, "utf8");
  } finally {
    closeSync(fd);
  }
}

/** Read a JSON file, refusing symlinks and oversized files. */
export function readJson(path: string): unknown {
  return JSON.parse(readText(path));
}

/** The render-relevant fields of one spec shape, in a fixed key order. */
function pick(s: SpecShape): ShapeData {
  return {
    id: s.id,
    version: s.version,
    category: s.category,
    names: {
      en: s.names.en,
      ckb: { text: s.names.ckb.text, status: s.names.ckb.status },
      kmr: { text: s.names.kmr.text, status: s.names.kmr.status },
    },
    aliases: s.aliases,
    tags: s.tags,
    layers: s.layers,
    symmetry: s.symmetry,
    parameters: s.parameters,
    primitives: s.primitives,
  };
}

/** The generated module's source text. */
export function generateShapes(specDir: string = SPEC_DIR): string {
  const catalog = readJson(join(specDir, "catalog.json")) as Catalog;
  const lines: string[] = [];
  const seen = new Set<string>();
  for (const category of catalog.categories) {
    for (const id of category.shapes) {
      if (typeof id !== "string" || !ID.test(id))
        throw new Error(`bad shape id ${JSON.stringify(id)}`);
      if (seen.has(id)) throw new Error(`duplicate shape id ${id}`);
      seen.add(id);
      const shape = readJson(join(specDir, "shapes", `${id}.json`)) as SpecShape;
      if (shape.id !== id)
        throw new Error(`spec/shapes/${id}.json has id ${JSON.stringify(shape.id)}`);
      lines.push(`  ${JSON.stringify(pick(shape))},`);
    }
  }
  return [
    "// Generated by scripts/generate-shapes.ts from spec/catalog.json and spec/shapes/.",
    "// Do not edit: run `pnpm --filter @0xdolan/deq-core generate`.",
    'import type { ShapeData } from "../types.js";',
    "",
    "/** Every catalog shape, in catalog order. */",
    "export const SHAPES: readonly ShapeData[] = [",
    ...lines,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generateShapes();
  if (process.argv.includes("--check")) {
    if (readText(OUT_FILE, 1024 * 1024) !== text) {
      console.error(`${OUT_FILE} is out of date: run \`pnpm --filter @0xdolan/deq-core generate\``);
      process.exit(1);
    }
  } else {
    writeFileSync(OUT_FILE, text);
  }
}
